"""Generate research/FINAL_RESULTS.md — the single source of truth for the papers.

EVERY number in the output is read from the committed artifacts (no typed
numbers): cross_conformal_summary.json, diagnostics.json,
external_halide_diagnostics.json, distance_q.json. The approved paper wording
and the forbidden-claims list are ASSEMBLED from those values and asserted
against the exact strings the paper must use, so artifact drift fails the
script instead of silently publishing stale numbers.

Run from repo root:
    .venv311/Scripts/python.exe crystal_gnn/scripts/final_results_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LOCO = REPO / "materials-screening-ai" / "research" / "loco_cross_conformal"
OUT = REPO / "materials-screening-ai" / "research" / "FINAL_RESULTS.md"

APPROVED_WORDING = (
    "10-fold leave-one-cluster-out, nested; 89.6% pooled / 92.2% macro at "
    "q_LOFO; 71.2% at shipped q; worst fold 7 (75.1%)"
)


def pct(x: float) -> str:
    return f"{100.0 * x:.1f}%"


def main() -> None:
    summary = json.loads((LOCO / "cross_conformal_summary.json").read_text(encoding="utf-8"))
    diag = json.loads((LOCO / "diagnostics.json").read_text(encoding="utf-8"))
    ext = json.loads((LOCO / "external_halide_diagnostics.json").read_text(encoding="utf-8"))
    dq = json.loads((LOCO / "distance_q.json").read_text(encoding="utf-8"))

    nested = summary["nested_lofo_result"]
    pooled = summary["pooled_q90_non_nested"]
    per_fold = summary["per_fold"]
    shipped_pool = summary["pooled_coverage_at_shipped_q"]
    shipped_macro = summary["macro_coverage_at_shipped_q"]
    q_shipped = summary["q_shipped"]
    coverage_target = summary["coverage_target"]

    worst = min(per_fold, key=lambda r: r["coverage_cross_conformal"])
    generated_wording = (
        f"10-fold leave-one-cluster-out, nested; "
        f"{pct(nested['pooled_coverage'])} pooled / {pct(nested['macro_coverage'])} "
        f"macro at q_LOFO; {pct(shipped_pool)} at shipped q; "
        f"worst fold {worst['cluster']} ({pct(worst['coverage_cross_conformal'])})"
    )
    assert generated_wording == APPROVED_WORDING, (
        f"approved wording drifted from artifacts:\n  generated: {generated_wording}\n"
        f"  approved:  {APPROVED_WORDING}"
    )

    # (a) nested LOFO per-fold table -------------------------------------
    lines = []
    lines.append("| fold | n | nested LOFO q | nested coverage | coverage @ shipped q |")
    lines.append("|---|---:|---:|---:|---:|")
    for r in sorted(per_fold, key=lambda r: r["cluster"]):
        lines.append(
            f"| {r['cluster']} | {r['n_test']} | {r['q_cross_conformal']:.4f} | "
            f"{pct(r['coverage_cross_conformal'])} | {pct(r['coverage_at_shipped_q_1p0254'])} |"
        )
    table = "\n".join(lines)
    pf_nested = sorted(r["coverage_cross_conformal"] for r in per_fold)

    # (c) fold-7 diagnosis ------------------------------------------------
    f7 = diag["fold7"]["composition_fold7"]
    f7_cls = f7["class_pct"]
    audit7 = dq["own_train_distance_audit"]["7"]
    others7 = dq["own_train_distance_audit"]
    med_d = {k: v["median_d_own_train"] for k, v in others7.items()}
    med_d_others = sorted(v for k, v in med_d.items() if k != "7")

    # (d) external halide --------------------------------------------------
    dec = ext["coverage_decomposition"]
    ext_sigma_ratio = dec["verdict_inputs"]["median_sigma_ratio_ext_over_loco"]
    ext_mae_ratio = dec["verdict_inputs"]["mae_ratio_ext_over_loco"]
    loco_pb = dec["loco_pb_halide_subset"]

    # (e) distance-q decision ---------------------------------------------
    agg = dq["aggregates"]
    dec_rule = dq["decision_rule"]
    db = dq["nested_distance_bin_q"]
    lofo_same = dq["global_nested_q_lofo_same_points"]
    shipped_line = dq["shipped_q"]
    bin_covs = [b["nested_cov"] for b in db["coverage_by_distance_bin"]]
    quint = dq["coverage_by_distance_quintile_at_shipped_q"]

    # (g) forbidden claims, numbers generated ------------------------------
    oracle_q = f"{summary['shift_aware_q_exact']:.4f}"
    assert oracle_q == "1.8143", f"oracle q drifted: {oracle_q}"

    md = f"""# FINAL_RESULTS — single source of truth for the papers

Generated by `crystal_gnn/scripts/final_results_report.py` from the committed
artifacts in `research/loco_cross_conformal/`. Do not edit by hand; rerun the
script after regenerating artifacts.

## (a) Nested LOCO coverage, per fold

Nested leave-one-fold-out q: fold c's q is the {pct(coverage_target)} quantile of
the OTHER 9 folds' scores, applied to fold c (never own-fold).

{table}

Per-fold nested coverage (from the artifact): min {pct(nested['per_fold_coverage']['min'])} (fold {worst['cluster']}),
Q1 {pct(nested['per_fold_coverage']['q1'])}, median {pct(nested['per_fold_coverage']['median'])},
Q3 {pct(nested['per_fold_coverage']['q3'])}, max {pct(nested['per_fold_coverage']['max'])}.

## (b) Pooled / macro coverage

| q | pooled | macro | median half-width |
|---|---:|---:|---:|
| shipped q = {q_shipped} | {pct(shipped_pool)} | {pct(shipped_macro)} | — |
| nested LOFO q (per fold, PRIMARY) | {pct(nested['pooled_coverage'])} | {pct(nested['macro_coverage'])} | {nested['median_half_width_eV']:.4f} eV |
| pooled 10-fold q = {pooled['q']} (single q, non-nested fit) | — | {pct(pooled['macro_coverage'])} | {pooled['median_half_width_eV']:.4f} eV |

- Nested LOFO q spread: {nested['q_spread']['min']}–{nested['q_spread']['max']} (median {nested['q_spread']['median']}).
- Pooled q = {pooled['q']} applied to every fold: per-fold min {pct(pooled['per_fold_coverage']['min'])},
  Q1 {pct(pooled['per_fold_coverage']['q1'])}, median {pct(pooled['per_fold_coverage']['median'])},
  Q3 {pct(pooled['per_fold_coverage']['q3'])}; macro {pct(pooled['macro_coverage'])}.
  (Non-nested fit — own-fold scores contribute to q; reported with that caveat.)
- Oracle-only (NOT a result, not adopted): own-fold q = {oracle_q}.
  Role recorded in the artifact: {summary['shift_aware_q_role']}.

## (c) Fold {worst['cluster']} diagnosis

- Nested coverage {pct(worst['coverage_cross_conformal'])} at q_LOFO = {worst['q_cross_conformal']},
  {pct(worst['coverage_at_shipped_q_1p0254'])} at shipped q (n = {worst['n_test']}),
  test MAE {worst['test_mae_eV_per_atom']:.4f} eV/atom vs pooled median-score context in diagnostics.json.
- Composition: {f7_cls.get('other', 0)}% "other" (chalcogenide/halide-heavy), {f7_cls.get('halide_other', 0)}% halide_other,
  {f7['pb_halide_pct']}% pb_halide; top elements {', '.join(f7['top_elements'][:6])}.
  Pooled other-9 baseline: {diag['fold7']['composition_pooled_other9']['class_pct'].get('other', 0)}% "other".
- Novelty: median SOAP-sketch distance to its OWN train = {med_d['7']}
  (all other folds: {med_d_others[0]}–{med_d_others[-1]}) — fold {worst['cluster']} is by far the most
  out-of-distribution cluster.
- Per-bin sigma calibration and fold-7 composition details: diagnostics.json `fold7`.

## (d) External halide set caveat — do NOT cite as confirmation

- n = {ext['n']}; all Pb-halide by construction; overlap with the production train
  (idx < 50000) = {ext['overlap_summary']['in_production_train0_idx_lt_50000']};
  only {ext['overlap_summary']['within_checkpoint_data_cutoff']['n_idx_lt_50000']} of them sit inside the
  checkpoint's data cutoff ({ext['n_beyond_checkpoint_cutoff']} beyond it).
- Coverage {pct(dec['external']['coverage_at_Q'])} at shipped q vs {pct(dec['loco_pooled']['coverage_at_Q'])} LOCO pooled is
  driven by sigma inflation: median sigma {dec['external']['median_sigma']} vs {dec['loco_pooled']['median_sigma']}
  ({ext_sigma_ratio}x) while MAE is only {ext_mae_ratio}x; median score
  {dec['external']['median_score']} vs {dec['loco_pooled']['median_score']}.
- LOCO's OWN Pb-halide subset (n = {loco_pb['n']}) covers only {pct(loco_pb['coverage_at_Q'])} at shipped q —
  the external set looks better precisely because DER sigma inflates out-of-domain
  (conservative), not because calibration transfers.

## (e) Distance-conditional q — decision per the rule

Rule: ship as an optional mode iff min AND Q1 per-fold coverage improve over the
global nested LOFO q AND median half-width <= 1.03x.

- min: {agg['distance_q']['min']} vs {agg['global_nested_lofo']['min']} (improved = {str(dec_rule['improved_min']).lower()})
- Q1: {agg['distance_q']['q1']} vs {agg['global_nested_lofo']['q1']} (improved = {str(dec_rule['improved_q1']).lower()})
- median half-width ratio: {dec_rule['median_half_width_ratio']} (within 3% = {str(dec_rule['width_within_3pct']).lower()})
- **Outcome: {dec_rule['outcome']}** (flag-gated in serving: `shift_aware` / `MATSCREEN_SHIFT_AWARE_Q`;
  default remains shipped q = {q_shipped}).

Detail (distance-q vs global nested LOFO, same points):

| metric | distance-bin q | global nested LOFO q |
|---|---:|---:|
| pooled | {pct(db['pooled_cov'])} | {pct(lofo_same['pooled_cov'])} |
| macro | {pct(db['macro_cov'])} | {pct(nested['macro_coverage'])} |
| fold {worst['cluster']} | {pct(db['fold7_cov'])} | {pct(lofo_same['fold7_cov'])} |
| median half-width | {db['median_half_width_eV']:.4f} eV | {lofo_same['median_half_width_eV']:.4f} eV |
| min / Q1 / median fold cov | {agg['distance_q']['min']} / {agg['distance_q']['q1']} / {agg['distance_q']['median']} | {agg['global_nested_lofo']['min']} / {agg['global_nested_lofo']['q1']} / {agg['global_nested_lofo']['median']} |

- Per-bin nested coverage (10 train-distance deciles): {', '.join(str(c) for c in bin_covs)}.
- Shipped-q coverage by distance quintile: {', '.join(pct(b['coverage_at_shipped_q']) for b in quint)}
  (median score {quint[0]['median_score']} -> {quint[-1]['median_score']}).
- Shipped-q baseline on the same points: {pct(shipped_line['pooled_cov'])} pooled,
  {pct(shipped_line['fold7_cov'])} fold {worst['cluster']}.
- Per-fold paired deltas: distance_q.json `paired_per_fold_vs_global_nested`.
- Serving artifact provenance: distances are to each fold's OWN train split
  (out-of-sample; audit in distance_q.json `own_train_distance_audit`).

## (f) Exact approved wording for the paper

> {APPROVED_WORDING}

## (g) Claims the paper must NOT make

1. {oracle_q} as a result — it is a NON-NESTED own-fold oracle only, not adopted.
2. "{coverage_target * 100:.0f}% coverage under shift" for the shipped q — measured is {pct(shipped_pool)} pooled
   / {pct(shipped_macro)} macro at q = {q_shipped}.
3. Pb-halide certification — LOCO's own Pb-halide subset covers {pct(loco_pb['coverage_at_Q'])}
   (n = {loco_pb['n']}); no class-conditional guarantee is claimed.
4. The external set ({ext['n']} Pb-halides, {pct(dec['external']['coverage_at_Q'])}) as confirmation — its coverage comes from
   {ext_sigma_ratio}x sigma inflation, not transfer (see (d)).
"""

    OUT.write_text(md, encoding="utf-8")
    print(md)
    print(f"\nwrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
